"""
PROJECT NOVA - Local News Database Retriever (Milestone 7 & 9)
=============================================================
Directly queries the 24/7 Live News Ingestion Database (news_database.db).
Bypasses internet scraping latency (<0.05s response time) using SQLite FTS5 BM25 search.
Converts stored records into ExtractedDocument evidence blocks for grounded LLM synthesis.
"""

import logging
import sqlite3
from pathlib import Path
from typing import List, Optional
from retriever.models import ExtractedDocument

logger = logging.getLogger("nova.news_retriever")

# Path to the live news database generated by live_news_scraper
DEFAULT_DB_PATH = Path(__file__).resolve().parent.parent.parent / "live_news_scraper/data/news_database.db"


STOPWORDS = {
    "tell", "me", "who", "won", "have", "has", "had", "the", "a", "an", "record", "of",
    "in", "on", "at", "to", "for", "and", "or", "between", "first", "last", "what", "is",
    "are", "was", "were", "which", "team", "match", "latest", "update", "news", "about",
    "today", "yesterday", "current", "reports", "indicate", "that", "this", "some", "with",
    "from", "give", "show", "can", "you", "does", "did", "their", "there"
}


class LocalNewsRetriever:
    """Retrieves freshly ingested news articles from the local SQLite FTS5 database."""

    def __init__(self, db_path: Optional[Path] = None):
        self.db_path = db_path or DEFAULT_DB_PATH

    def is_available(self) -> bool:
        return self.db_path.exists()

    def search(self, query: str, limit: int = 3, category: Optional[str] = None) -> List[ExtractedDocument]:
        """
        Executes strict BM25 search against the local news database.
        Ensures high semantic relevance; rejects loose single-word false matches.
        """
        if not self.is_available():
            logger.warning(f"News database not found at {self.db_path}")
            return []

        import re

        # Extract meaningful keywords excluding common stopwords
        raw_words = [re.sub(r"[^\w]", "", w.lower()) for w in query.split()]
        significant_tokens = [w for w in raw_words if len(w) > 2 and w not in STOPWORDS]

        if not significant_tokens:
            return []

        # Build FTS5 tokens (exact match for numbers and short words, prefix match for longer words)
        formatted_tokens = []
        for t in significant_tokens:
            if t.isdigit() or len(t) <= 4:
                formatted_tokens.append(f'"{t}"')
            else:
                formatted_tokens.append(f'"{t}"*')

        # Use AND search for top terms if multiple
        if len(formatted_tokens) >= 2:
            fts_query = " AND ".join(formatted_tokens[:3])
        else:
            fts_query = formatted_tokens[0]

        sql = """
            SELECT a.article_id, a.source_id, a.url, a.title, a.author, a.published_at,
                   a.category, a.content, a.word_count,
                   bm25(articles_fts) as rank
            FROM articles_fts f
            JOIN articles a ON a.article_id = f.article_id
            WHERE articles_fts MATCH ?
        """
        params = [fts_query]
        if category:
            sql += " AND a.category = ?"
            params.append(category)

        sql += " ORDER BY rank LIMIT ?"
        params.append(limit)

        results: List[ExtractedDocument] = []
        try:
            conn = sqlite3.connect(str(self.db_path), timeout=5.0)
            conn.row_factory = sqlite3.Row
            cursor = conn.execute(sql, params)
            rows = cursor.fetchall()

            for idx, r in enumerate(rows, start=1):
                clean_content = r["content"]
                # Strict verification: At least half the significant tokens must appear in title or content
                matched_count = sum(1 for token in significant_tokens if token in clean_content.lower() or token in r["title"].lower())
                if matched_count < min(2, len(significant_tokens)):
                    continue

                results.append(
                    ExtractedDocument(
                        source_index=idx,
                        title=r["title"] or "News Article",
                        url=r["url"],
                        clean_text=clean_content,
                        published_date=r["published_at"],
                        author=r["author"],
                        word_count=r["word_count"] or len(clean_content.split()),
                        is_success=True,
                    )
                )

            conn.close()
            if results:
                logger.info(f"Local News DB returned {len(results)} verified relevant articles for '{query}'")

        except Exception as e:
            logger.error(f"Error querying local news DB: {e}")

        return results

